import { QueryClient } from '@tanstack/react-query';

/** Shared singleton — every mutation invalidates against this instance. */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 30_000,
      refetchOnWindowFocus: false,
      retry: 1,
    },
    mutations: {
      retry: 0,
    },
  },
});
